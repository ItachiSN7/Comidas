List<Meal> getMealsForType(String mealType) =>
    mockMeals.where((m) => m.mealType == mealType).toList();

List<Meal> getRecommendedMeals({
  required String mealType,
  required double remainingCalories,
  required double remainingProtein,
  required double remainingFat,
  required String goal,
}) {
  var meals = getMealsForType(mealType);

  // Sort by relevance to remaining macros
  if (remainingFat < 10) {
    meals.sort((a, b) => a.fat.compareTo(b.fat));
  } else if (remainingCalories < 300) {
    meals.sort((a, b) => a.calories.compareTo(b.calories));
  } else if (remainingProtein > 30) {
    meals.sort((a, b) => b.protein.compareTo(a.protein));
  }

  return meals.take(3).toList();
}
